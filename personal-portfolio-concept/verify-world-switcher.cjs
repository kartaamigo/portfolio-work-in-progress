const { chromium } = require('C:/Users/1/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(pathToFileURL(path.join(__dirname, 'combined.html')).href);
  await page.evaluate(() => document.fonts.ready);
  const art = page.locator('.world-selector [data-switch="art"]');
  const digital = page.locator('.world-selector [data-switch="digital"]');
  const world = () => page.getAttribute('body', 'data-world');
  const overflow = () => page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(await world(), 'neutral');
  assert.equal(await page.locator('.artwork-neutral').count(), 0);
  assert(!await page.locator('.portfolio-content').isVisible());
  await art.hover();
  await page.waitForTimeout(500);
  assert.equal(await world(), 'neutral');
  await art.focus();
  assert.equal(await world(), 'neutral');
  await page.screenshot({ path: path.join(__dirname, 'switcher-center.png') });
  await art.click();
  await page.waitForTimeout(850);
  assert.equal(await world(), 'art');
  assert(await page.locator('.portfolio-content').isVisible());
  assert.equal(await art.getAttribute('aria-pressed'), 'true');
  assert.equal(await digital.getAttribute('aria-pressed'), 'false');
  assert.equal(await page.locator('.work-a').evaluate(element => getComputedStyle(element).position), 'sticky');
  await page.screenshot({ path: path.join(__dirname, 'switcher-soulart.png') });
  await page.evaluate(() => window.scrollTo({ top: document.querySelector('.works').getBoundingClientRect().top + scrollY - 100, behavior: 'instant' }));
  await page.waitForTimeout(1000);
  await page.screenshot({ path: path.join(__dirname, 'soulart-projects-start.png') });
  await page.evaluate(() => window.scrollTo({ top: document.querySelectorAll('.art-stack-anchor')[1].getBoundingClientRect().top + scrollY - 130, behavior: 'instant' }));
  await page.waitForTimeout(1000);
  const top = await page.locator('.work-a').evaluate(element => element.getBoundingClientRect().top);
  const headerHeight = await page.locator('body>header').evaluate(element => element.getBoundingClientRect().height);
  assert(Math.abs(top - headerHeight - 20) < 5, 'First project should remain pinned');
  await page.screenshot({ path: path.join(__dirname, 'soulart-projects-stack.png') });
  await page.locator('.world-center-return').click();
  assert.equal(await world(), 'neutral');
  assert(!await page.locator('.portfolio-content').isVisible());
  await digital.click();
  await page.waitForTimeout(850);
  assert.equal(await world(), 'digital');
  assert.equal(await art.getAttribute('aria-pressed'), 'false');
  assert.equal(await digital.getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('.work-a').evaluate(element => getComputedStyle(element).position), 'static');
  await page.screenshot({ path: path.join(__dirname, 'switcher-reform.png') });
  await digital.click();
  assert.equal(await world(), 'neutral');
  await art.focus();
  await art.press('Enter');
  assert.equal(await world(), 'art');
  await page.keyboard.press('Escape');
  assert.equal(await world(), 'neutral');
  await page.locator('header nav a[href="#about"]').click();
  await page.waitForTimeout(1200);
  assert.equal(await world(), 'art');
  assert(await page.locator('#about').isVisible());
  assert.equal(await page.locator('.resume-block').count(), 4);
  assert(await page.evaluate(() => !!(document.getElementById('about').compareDocumentPosition(document.getElementById('projects')) & Node.DOCUMENT_POSITION_FOLLOWING)));
  assert.equal(await page.locator('a[href="mailto:xghostxsoulx@gmail.com"]').count(), 1);
  assert(!/отзывы|testimonials|what clients say/i.test(await page.locator('.portfolio-content').innerText()));
  await page.locator('.world-center-return').click();
  for (const [width, height] of [[1024,768],[1366,768],[1920,1080],[2560,1440],[390,844],[320,740]]) {
    await page.setViewportSize({ width, height });
    for (const state of ['neutral','art','digital']) {
      await page.evaluate(state => choose(state), state);
      await page.waitForTimeout(200);
      assert(!await overflow(), 'Overflow at ' + width + ': ' + state);
      const bounds = await page.locator('.world-selector').boundingBox();
      assert(bounds.x >= 0 && bounds.x + bounds.width <= width + 1, 'Selector outside viewport');
    }
    if (width <= 800) assert.equal(await page.locator('.work-a').evaluate(element => getComputedStyle(element).position), 'static');
    console.log('PASS: three modes fit ' + width + 'x' + height);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => choose('neutral'));
  await page.waitForTimeout(500);
  await page.screenshot({ path: path.join(__dirname, 'switcher-mobile-center.png') });
  await art.click();
  await page.waitForTimeout(850);
  await page.screenshot({ path: path.join(__dirname, 'switcher-mobile-soulart.png') });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await page.locator('.art-reveal').first().evaluate(element => getComputedStyle(element).transitionDuration), '0s');
  await page.evaluate(() => choose('digital'));
  assert.equal(await page.locator('.motion-card').evaluate(element => getComputedStyle(element).animationName), 'none');
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: click-only toggles, exclusive worlds, sticky projects, no testimonials, resume order, keyboard and reduced motion.');
})();
